create table public.users
(
    id           bigint generated by default as identity
        constraint pk_users
        primary key,
    display_name varchar(50)                                                  not null,
    oidc_issuer  text                                                         not null,
    oidc_subject varchar(255)                                                 not null,
    email        varchar(255),
    status       varchar(20)              default 'ACTIVE'::character varying not null
        constraint ck_users_status
            check ((status)::text = ANY
                   ((ARRAY ['ACTIVE'::character varying, 'SUSPENDED'::character varying])::text[])),
    created_at   timestamp with time zone default CURRENT_TIMESTAMP           not null,
    updated_at   timestamp with time zone default CURRENT_TIMESTAMP           not null,
    constraint uq_users_oidc
        unique (oidc_issuer, oidc_subject)
);

comment on table public.users is '회원';

comment on column public.users.id is '회원_ID';

comment on column public.users.display_name is '표시_이름';

comment on column public.users.oidc_issuer is 'OIDC_발급자';

comment on column public.users.oidc_subject is 'OIDC_유저_식별자';

comment on column public.users.email is '이메일';

comment on column public.users.status is '상태';

comment on column public.users.created_at is '생성일시';

comment on column public.users.updated_at is '수정일시';
