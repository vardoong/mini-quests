CREATE TABLE public.user_quests
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT                   NOT NULL,
    quest_id     BIGINT                   NOT NULL,
    status       VARCHAR(20)              NOT NULL DEFAULT 'IN_PROGRESS',
    started_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_user_quests PRIMARY KEY (id),
    CONSTRAINT uq_user_quests_user_quest UNIQUE (user_id, quest_id),
    CONSTRAINT fk_user_quests_quest
        FOREIGN KEY (quest_id) REFERENCES public.quests (id),
    CONSTRAINT ck_user_quests_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_user_quests_completion
        CHECK (
            (status = 'IN_PROGRESS' AND completed_at IS NULL)
                OR (status = 'COMPLETED' AND completed_at IS NOT NULL)
            )
);

CREATE INDEX ix_user_quests_quest_id ON public.user_quests (quest_id);
